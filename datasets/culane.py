from pathlib import Path
from PIL import Image
from torch.utils.data import Dataset


class CULaneDataset(Dataset):
    """
    CULane image dataset loader for OA-LoRA.

    This loader reads the reproducibly selected CULane images
    generated by prepare_culane.py.

    Expected directory structure:

    selected_images/
    ├── 000001.jpg
    ├── 000002.jpg
    ├── ...
    └── 002000.jpg
    """

    IMAGE_EXTENSIONS = {
        ".jpg",
        ".jpeg",
        ".png",
        ".JPG",
        ".JPEG",
        ".PNG",
    }

    def __init__(
        self,
        root_dir,
        transform=None,
    ):
        self.root_dir = Path(root_dir)
        self.transform = transform

        if not self.root_dir.exists():
            raise FileNotFoundError(
                f"CULane dataset directory not found: {self.root_dir}"
            )

        self.images = sorted(
            [
                path
                for path in self.root_dir.rglob("*")
                if path.is_file()
                and path.suffix in self.IMAGE_EXTENSIONS
            ],
            key=lambda path: path.as_posix().lower(),
        )

        if len(self.images) == 0:
            raise RuntimeError(
                f"No images found in CULane directory: {self.root_dir}"
            )

        print(
            f"CULane dataset loaded: "
            f"{len(self.images)} images"
        )

    def __len__(self):
        return len(self.images)

    def __getitem__(self, index):

        image_path = self.images[index]

        image = Image.open(
            image_path
        ).convert("RGB")

        if self.transform is not None:
            image = self.transform(image)

        return {
            "image": image,
            "path": str(image_path),
        }


